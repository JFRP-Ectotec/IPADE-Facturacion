    ON (tgt.TVRSDSQ_SDOC_CODE = src.TVRSDSQ_SDOC_CODE
        AND tgt.TVRSDSQ_FBPR_CODE = src.TVRSDSQ_FBPR_CODE
        AND tgt.TVRSDSQ_SEQ_NUM = src.TVRSDSQ_SEQ_NUM)

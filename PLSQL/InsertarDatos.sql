    USING (SELECT 'NDC' as TVRSDSQ_SDOC_CODE,
        'FACTURACION' as TVRSDSQ_FBPR_CODE,
        1 as TVRSDSQ_SEQ_NUM,
        1 as TVRSDSQ_MAX_SEQ,
        1 as TVRSDSQ_INIT_SEQ,
        9999999 as TVRSDSQ_FINAL_SEQ,

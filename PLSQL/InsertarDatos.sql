MERGE INTO TVVSDOC tgt
    USING (
        SELECT 'NDC' as TVVSDOC_CODE,
            'Notas de Crédito' as TVVSDOC_DESC,
            'Y' as TVVSDOC_INC_TAX,
            'A' as TVVSDOC_GMODE,
            'Y' as TVVSDOC_PREFIX1_IND,
            'N' as TVVSDOC_PREFIX2_IND,
            USER as TVVSDOC_USER_ID,
            'Carga_Inicial' as TVVSDOC_DATA_ORIGIN
        FROM dual
    ) src
    ON (tgt.TVVSDOC_CODE=src.TVVSDOC_CODE)
    WHEN MATCHED
    THEN UPDATE SET
        tgt.TVVSDOC_DESC=src.TVVSDOC_DESC, 
        tgt.TVVSDOC_INC_TAX=src.TVVSDOC_INC_TAX, 
        tgt.TVVSDOC_GMODE=src.TVVSDOC_GMODE, 
        tgt.TVVSDOC_PREFIX1_IND=src.TVVSDOC_PREFIX1_IND, 
        tgt.TVVSDOC_PREFIX2_IND=src.TVVSDOC_PREFIX2_IND, 
        tgt.TVVSDOC_ACTIVITY_DATE=SYSDATE, tgt.TVVSDOC_USER_ID=src.TVVSDOC_USER_ID, 
        tgt.TVVSDOC_DATA_ORIGIN=src.TVVSDOC_DATA_ORIGIN
    WHEN NOT MATCHED
    THEN INSERT (TVVSDOC_CODE, TVVSDOC_DESC, TVVSDOC_INC_TAX, TVVSDOC_GMODE, TVVSDOC_PREFIX1_IND, 
        TVVSDOC_PREFIX2_IND, TVVSDOC_ACTIVITY_DATE, TVVSDOC_USER_ID, TVVSDOC_DATA_ORIGIN)
    VALUES (src.TVVSDOC_CODE, src.TVVSDOC_DESC, src.TVVSDOC_INC_TAX, src.TVVSDOC_GMODE, src.TVVSDOC_PREFIX1_IND, 
        src.TVVSDOC_PREFIX2_IND, SYSDATE, src.TVVSDOC_USER_ID, src.TVVSDOC_DATA_ORIGIN);


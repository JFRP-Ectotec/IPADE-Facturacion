(GZVPRMH_CODE, GZVPRMH_DESC, GZVPRMH_CREATE_DATE, GZVPRMH_ACTIVITY_DATE, GZVPRMH_USER_ID, 
GZVPRMH_DATA_ORIGIN)
VALUES('FACTPAYLINEA', 'Tipos de pago para facturar en pago en línea', SYSDATE, SYSDATE, USER, 
'Carga Inicial');

DECLARE
    secuencial NUMBER;
    header_grupo gzvprmh.gzvprmh_code%TYPE := 'FACTPAYLINEA';
BEGIN
    FOR i IN (
        SELECT '04' as codigo, 'Tarjeta de Crédito' as descripcion FROM dual
        UNION
        SELECT '28' as codigo, 'Tarjeta de Débito' as descripcion FROM dual
    ) LOOP
        SELECT NVL(MAX(gzvprmd_seq_no), 0) + 1
        INTO secuencial
        FROM GZVPRMD
        WHERE gzvprmd_prmh_code = header_grupo
            AND gzvprmd_internal_code = i.codigo;
        
        INSERT INTO GZVPRMD (
            GZVPRMD_PRMH_CODE, GZVPRMD_SEQ_NO, GZVPRMD_INTERNAL_CODE, GZVPRMD_SHORT_EXTERNAL, GZVPRMD_EXTERNAL_CODE, 
            GZVPRMD_COMMENTS, GZVPRMD_CREATE_DATE, GZVPRMD_ACTIVITY_DATE, GZVPRMD_USER_ID, GZVPRMD_DATA_ORIGIN
        ) VALUES (
            header_grupo, secuencial, i.codigo, i.descripcion, '', 
            i.descripcion, SYSDATE, SYSDATE, USER, 'Carga Inicial');
    END LOOP;
        
    COMMIT;
END;

